    private List<String> requireSpaceView(Long spaceId, User user) {
        ThrowUtils.throwIf(spaceId == null || spaceId <= 0, ErrorCode.PARAMS_ERROR);
        Space space = spaceService.getById(spaceId);
        ThrowUtils.throwIf(space == null, ErrorCode.NOT_FOUND_ERROR, "空间不存在");
        List<String> permissions = spaceUserAuthManager.getPermissionList(space, user);
        ThrowUtils.throwIf(!permissions.contains(SpaceUserPermissionConstant.PICTURE_VIEW), ErrorCode.NO_AUTH_ERROR);
        return permissions;
    }

    private List<String> getViewPermissions(Picture picture, HttpServletRequest request) {
        if (picture.getSpaceId() != null) {
            return requireSpaceView(picture.getSpaceId(), userService.getLoginUser(request));
        }
        User user = null;
        try {
            user = userService.getLoginUser(request);
        } catch (BusinessException e) {
            if (e.getCode() != ErrorCode.NOT_LOGIN_ERROR.getCode()) throw e;
        }
        if (user != null && (Objects.equals(picture.getUserId(), user.getId()) || userService.isAdmin(user))) {
            return spaceUserAuthManager.getPermissionsByRole(SpaceRoleEnum.ADMIN.getValue());
        }
        ThrowUtils.throwIf(!Objects.equals(picture.getReviewStatus(), PictureReviewStatusEnum.PASS.getValue()),
                ErrorCode.NO_AUTH_ERROR);
        return Collections.singletonList(SpaceUserPermissionConstant.PICTURE_VIEW);
    }
